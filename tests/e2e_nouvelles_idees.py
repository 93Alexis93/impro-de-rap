# Tests Playwright (29/10/2026). Lancer depuis la racine : python3 -m http.server 8765 & puis python3 tests/e2e_nouvelles_idees.py
import sys,time
from playwright.sync_api import sync_playwright
URL="http://localhost:8765/index.html"
res=[]
def ok(c,m):
    res.append((bool(c),m));print(("PASS " if c else "FAIL ")+m,flush=True)
with sync_playwright() as p:
    b=p.chromium.launch(args=["--use-fake-ui-for-media-stream","--use-fake-device-for-media-stream","--autoplay-policy=no-user-gesture-required"])
    ctx=b.new_context(viewport={"width":375,"height":812},permissions=["microphone"])
    pg=ctx.new_page();errs=[]
    pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto(URL);pg.wait_for_timeout(500)
    # ---- 1. Instrus VirtualBeat dans le Freestyle
    pg.click("#enterFreestyle")
    opts=pg.eval_on_selector_all("#freeBeat option","os=>os.map(o=>o.value)")
    ok(opts==["none","virtual-boom","virtual-lofi","virtual-oriental","virtual-makossa","virtual-trap","file"],"Freestyle : mêmes 5 instrus que l'Impro + sans instru + import")
    pg.select_option("#freeBeat","virtual-trap");ok(pg.input_value("#freeBpm")=="140","Trap règle le tempo à 140")
    pg.select_option("#freeBeat","virtual-boom");ok(pg.input_value("#freeBpm")=="90","Boom-bap règle le tempo à 90")
    pg.fill("#freeBpm","160");pg.dispatch_event("#freeBpm","change")
    pg.select_option("#freeMode","1");pg.uncheck("#freeIntro")
    text="Je marche dans la ville\nLe béton sous mes pieds\nLa nuit tombe tranquille\nJe garde le cap et la clé\nLigne cinq\nLigne six"
    pg.fill("#freeText",text);pg.fill("#freeTextTitle","Test prise")
    # ---- 2. enregistrement
    pg.check("#freeRecOn")
    pg.click("#freeStart");pg.wait_for_timeout(2500)
    st=pg.evaluate("()=>({idx:freeBeatIndex,synth:freeSynth,bus:!!freeVbBus,rec:!!freeRec&&freeRec.startedAt>0,state:freeRec&&freeRec.recorder.state,badge:!$('freeRecBadge').classList.contains('hide'),ctx:freeBeatContext&&freeBeatContext.state})")
    ok(st["idx"]>3 and st["synth"] and st["bus"],"Freestyle : le moteur VirtualBeat tourne (%d temps programmés)"%st["idx"])
    ok(st["rec"] and st["state"]=="recording" and st["badge"],"Enregistrement en cours + badge REC (%s)"%st)
    pg.click("#freePause");pg.wait_for_timeout(600)
    ok(pg.evaluate("()=>freeRec.recorder.state")=="paused","Pause : la prise est mise en pause")
    pg.click("#freePause");pg.wait_for_timeout(2500)
    pg.click("#freeStop");pg.wait_for_timeout(1500)
    rows=pg.locator("#freeTakes .recording-item").count()
    ok(rows==1,"Prise sauvegardée et listée (%d)"%rows)
    take=pg.evaluate("async()=>{const t=(await getFreeTakes())[0];return {n:t.timeline.length,dur:t.duration,size:t.blob.size,type:t.blob.type,tempo:t.tempo,lines:(t.html.match(/free-line/g)||[]).length,maxli:Math.max(...t.timeline.map(e=>e.li??-9))}}")
    ok(take["size"]>1000 and take["n"]>3 and take["tempo"] and take["lines"]==6,"Prise : audio + texte + chronologie (%s)"%take)
    ok(3500<take["dur"]<6500,"Durée hors pause cohérente (%d ms pour ~5 s jouées)"%take["dur"])
    pg.evaluate("()=>listRecordings()");pg.wait_for_timeout(300)
    ok("Test prise" not in pg.inner_text("#recordingsList"),"Les prises Freestyle n'apparaissent pas dans la liste de l'Impro")
    pg.click("#freeTakes .recording-item button:has-text('Réécouter')");pg.wait_for_timeout(2500)
    rp=pg.evaluate("()=>({vis:!$('freeReplay').classList.contains('hide'),t:$('freeReplayAudio').currentTime,on:[...$('freeReplayText').querySelectorAll('.free-line')].findIndex(e=>e.classList.contains('on'))})")
    ok(rp["vis"] and rp["t"]>1,"Réécoute lancée (%.1f s)"%rp["t"])
    ok(rp["on"]>=1,"Texte synchronisé : ligne %d en surbrillance pendant la réécoute"%rp["on"])
    pg.evaluate("()=>{const a=$('freeReplayAudio');a.currentTime=0}");pg.wait_for_timeout(400)
    on0=pg.evaluate("()=>[...$('freeReplayText').querySelectorAll('.free-line')].findIndex(e=>e.classList.contains('on'))")
    ok(on0<=1,"Retour au début de la prise : la surbrillance revient au début (%d)"%on0)
    pg.click("#freeReplayClose")
    # ---- 3. rimes en direct
    pg.evaluate("()=>{const t=$('freeText');t.focus();t.setSelectionRange(5,5)}");pg.dispatch_event("#freeText","click")
    pg.wait_for_function("()=>$('freeRhymeChips').childElementCount>0",timeout=30000);pg.wait_for_timeout(300)
    lab=pg.inner_text("#freeRhymeLabel");chips=pg.eval_on_selector_all("#freeRhymeChips button","bs=>bs.map(b=>b.firstChild.textContent)")
    ok("ville" in lab and 1<=len(chips)<=4,"Ligne touchée → rimes pour « ville » : %s"%chips)
    pg.evaluate("()=>{const t=$('freeText');t.value='Je marche dans la ville\\nLe béton sous mes pieds\\n';t.focus();t.setSelectionRange(t.value.length,t.value.length);t.dispatchEvent(new Event('input',{bubbles:true}))}")
    pg.wait_for_function("()=>$('freeRhymeLabel').textContent.includes('pieds')",timeout=5000)
    chips=pg.eval_on_selector_all("#freeRhymeChips button","bs=>bs.map(b=>b.firstChild.textContent)")
    ok(len(chips)>=1,"Nouvelle ligne → rimes pour « pieds » : %s"%chips)
    pg.click("#freeRhymeChips button >> nth=0");pg.wait_for_timeout(200)
    ok(pg.input_value("#freeText").rstrip().endswith(chips[0]),"Toucher une rime l'insère dans le texte")
    pg.uncheck("#freeRhymeOn");ok(not pg.is_visible("#freeRhymeChips button"),"Rimes en direct désactivables")
    pg.check("#freeRhymeOn")
    pg.click("#freeHome")
    # ---- 4. battle
    pg.click("#enterImpro");pg.wait_for_timeout(300)
    ok(pg.is_visible("#quickBattle") and pg.is_visible('[data-session-mode="battle"]'),"Battle visible : bouton rapide + carte « Mode d'impro »")
    pg.click("#quickBattle");pg.wait_for_timeout(600)
    ok(pg.is_visible("#battleP1") and pg.get_attribute('[data-session-mode="battle"]',"aria-pressed")=="true" and pg.is_checked("#battleMode"),"Bouton rapide : carte Battle sélectionnée, noms des MC affichés")
    pg.fill("#battleP1","Alexis");pg.fill("#battleP2","Léon");pg.dispatch_event("#battleP2","change")
    pg.select_option("#beatChoice","virtual-boom");pg.fill("#bpm","160");pg.select_option("#bars","2")
    pg.click("#launch");pg.wait_for_timeout(1200)
    t0=pg.inner_text("#battleBanner");ok("Alexis ouvre la battle" in t0,"Intro : « %s »"%t0.replace("\n"," | "))
    ok(pg.evaluate("()=>settings.bars")==4 and pg.input_value("#bars")=="2","Un mot toutes les 4 mesures pendant la battle, réglage « 2 mesures » conservé")
    pg.wait_for_function("()=>barIndex>=6",timeout=15000);b1=pg.inner_text("#battleBanner");cls1=pg.get_attribute("#battleBanner","class")
    ok("Alexis" in b1 and "p1" in cls1,"Tour 1 : micro à Alexis (%s)"%b1.replace("\n"," | "))
    w1=pg.inner_text("#bigWord")
    pg.wait_for_function("()=>barIndex>=8",timeout=10000);b8=pg.inner_text("#battleBanner")
    ok("Micro à Léon" in b8 and "warn" in pg.get_attribute("#battleBanner","class"),"Dernière mesure du tour : alerte (%s)"%b8.replace("\n"," | "))
    pg.wait_for_function("()=>barIndex>=10",timeout=10000);b2=pg.inner_text("#battleBanner");w2=pg.inner_text("#bigWord")
    ok("Léon" in b2 and "p2" in pg.get_attribute("#battleBanner","class") and w1!=w2,"Tour 2 : micro à Léon + nouveau mot (%s → %s)"%(w1,w2))
    pg.click("#finishBtn");pg.wait_for_timeout(500)
    ok("Battle : 2 passages" in pg.inner_text("#summaryLine"),"Bilan : "+pg.inner_text("#summaryLine"))
    ok(pg.is_hidden("#battleBanner"),"Bandeau masqué après la session")
    pg.click("#againBtn");pg.wait_for_timeout(800)
    ok("Alexis ouvre la battle" in pg.inner_text("#battleBanner"),"« Rejouer » relance bien une battle")
    pg.click("#finishBtn");pg.wait_for_timeout(300)
    pg.click("#improHome");pg.click("#enterImpro");pg.click('[data-session-mode="free"]');pg.click("#launch");pg.wait_for_timeout(800)
    ok(pg.is_hidden("#battleBanner") and pg.evaluate("()=>settings.bars")==2 and not pg.is_checked("#battleMode"),"Retour sur « Impro libre » : session normale, sans bandeau")
    pg.click("#finishBtn");pg.wait_for_timeout(300)
    # battle désactivée => pas de bandeau
    pg.click("#improHome") if pg.is_visible("#improHome") else None
    ok(not errs,"Aucune erreur JavaScript"+(": "+"; ".join(errs) if errs else ""))
    pg.screenshot(path=__import__("tempfile").gettempdir()+"/last.png")
    b.close()
print("\n%d/%d OK"%(sum(c for c,_ in res),len(res)))
sys.exit(0 if all(c for c,_ in res) else 1)
